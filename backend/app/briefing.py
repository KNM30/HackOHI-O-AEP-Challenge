"""One server-side computation shared by the briefing card and the assistant.

Recomputes risk, the fixed scenario and restoration from the request inputs (the
backend is the only source of numbers), then selects guidance and evaluates alerts.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass

from . import alerts, data_store, guidance, restoration, risk, scenarios
from . import schemas as s
from .context import supply_path
from .network import CircuitNetwork


class BriefingError(Exception):
    def __init__(self, status: int, detail: str):
        super().__init__(detail)
        self.status, self.detail = status, detail


@dataclass
class Bundle:
    net: CircuitNetwork
    premise: dict
    req: s.BriefingRequest
    risk: s.RiskResult
    impact: s.ScenarioResult | None
    restoration: s.RestorationResult | None
    scenario_key: str | None
    guidance: list[s.Recommendation]
    alerts: s.AlertsResult
    snapshot_version: str


def _hash(prefix: str, obj) -> str:
    return prefix + hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()[:10].upper()


def scenario_key(net: CircuitNetwork, location_ids: list[str]) -> str:
    """Identity of a fixed scenario definition (its damage locations), independent of crews."""
    return _hash("SCN-", [net.circuit_id, sorted(set(location_ids))])


def run_simulation(net: CircuitNetwork, p: dict, spec: s.SimulationSpec, crew: s.CrewParamsIn | None = None):
    scen = scenarios.resolve_fixed(net, spec.scenario_id, spec.scenario_label, spec.location_ids)
    impact = scenarios.evaluate(net, p, scen, scen.locations)
    params = restoration.CrewParams(**(crew or spec.crew).model_dump())
    rest = restoration.simulate(net, p, scen, params, data_store.labor_reference(), impact)
    return impact, rest


def compute(req: s.BriefingRequest) -> Bundle:
    try:
        found = data_store.find_premise(req.premise_id)
    except data_store.DataNotBuilt as e:
        raise BriefingError(503, str(e))
    if found is None:
        raise BriefingError(404, "unknown premise id")
    net, p = found
    if req.severity not in risk.cfg.SEVERITY:
        raise BriefingError(422, "unknown severity")
    path = supply_path(net, p.get("transformer_node"))
    rk = risk.assess(net, p, req.severity, path.approximated_gaps if path else 0)
    impact = rest = key = None
    if req.simulation:
        try:
            impact, rest = run_simulation(net, p, req.simulation)
        except (LookupError, ValueError) as e:
            raise BriefingError(422, str(e))
        key = scenario_key(net, req.simulation.location_ids)
    sel = rest.selected if rest else None
    recs = guidance.select(rk, sel, req.preferences, req.alerts.channel)
    al = alerts.evaluate(p["public_id"], rk, impact, rest, key, req.preferences, req.alerts, req.events,
                         req.last_notified, recs)
    version = _hash("SNP-", req.model_dump())
    return Bundle(net, p, req, rk, impact, rest, key, recs, al, version)


def response(b: Bundle) -> s.BriefingResponse:
    return s.BriefingResponse(
        snapshot_version=b.snapshot_version, scenario_key=b.scenario_key, premise_id=b.premise["public_id"],
        guidance=b.guidance,
        guidance_note=("Guidance is selected by fixed rules from your risk, the simulated scenario and needs you "
                       "declared in this session. Safety wording comes from the cited official pages; it is not "
                       "generated by AI."),
        alerts=b.alerts, restoration_kind=b.restoration.selected.range_kind if b.restoration else None)
